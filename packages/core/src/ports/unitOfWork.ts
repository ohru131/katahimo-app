/**
 * 複数のリポジトリにまたがる書き込みを、1つのトランザクションにまとめるためのポート。
 *
 * リポジトリ実装(@katahimo/db)はメソッドごとに `withTenant()` で自前のトランザクションを
 * 開く。単独の書き込みならそれで十分だが、「ドメインの行を書く」と「outbox_jobsに積む」の
 * ように2つの書き込みが揃って成立しなければ意味がない場面では、片方だけが確定してしまう。
 * 実際に問題になるのは次の2箇所:
 *
 * - 日報/事故報告/領収書/勤怠の保存 + ミラー要求のenqueue
 *   → 保存が通ってenqueueが落ちると、スプレッドシートへ永久に反映されないうえ、
 *     どのレコードが取り残されたのかを知る手段が無い。
 * - パスワード再設定コードの消費 + 新しいパスワードの書き込み
 *   → コードだけ焼かれてパスワードが変わらない。
 *
 * そこで、この UnitOfWorkPort でトランザクションを開き、その `TransactionScope` を
 * リポジトリメソッドの最後の引数に渡すと、同じトランザクションに相乗りする。
 *
 * 注意: `run()` のコールバックの中では、スコープを渡さないリポジトリ呼び出しをしないこと。
 * 単一接続のドライバ(公開デモのPGlite)では、内側で別のトランザクションを開こうとすると
 * 直列化キューで自分自身の完了を待ってしまい停止する。暗号化(tenant_keysの読み取り)や
 * 名前解決のような読み取りは、`run()` に入る前に済ませておく。
 */
export interface TransactionScope {
  /** このトランザクションが `SET LOCAL app.tenant_id` で束縛しているテナント。 */
  readonly tenantId: string;
}

export interface UnitOfWorkPort {
  /**
   * テナントスコープのトランザクションを開き、コールバックを実行する。
   * コールバックが例外を投げたらロールバックする。
   */
  run<T>(tenantId: string, fn: (scope: TransactionScope) => Promise<T>): Promise<T>;
}
